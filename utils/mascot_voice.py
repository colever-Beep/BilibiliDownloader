# 弹窗正文落款：短正文（<= SIGNOFF_MAX_LEN）末尾追加看板娘语气
SIGNOFF_MAX_LEN = 60
SIGNOFF = {
    "info": "  (｡•̀ᴗ-)✧ {喵～}",
    "warn": "  (；′⌒`) {要小心哦～}",
    "error": "  (；一_一) {别慌，看板娘在呢}",
    "success": "  ✧(≖ ◡ ≖✿) {嘿嘿～}",
    "confirm": "  (｡･ω･｡)ﾉ♡ {你说呢～}",
}


def suffix_for(key: str) -> str:
    """返回白名单文案的语气后缀；非白名单返回空串。

    传入的 key 必须是 tr() 的原始键（简体中文原文），不是译文。
    """
    if not ENABLED:
        return ""
    return _render(VOICE_SUFFIX.get(key, ""))


def badge_for(kind: str | None) -> str:
    """按看板娘表情类型返回标题徽标 emoji。"""
    if not ENABLED or not kind:
        return ""
    return TITLE_BADGE.get(kind, "")


def _has_voice(text: str) -> bool:
    """正文是否已带任一语气符号（白名单后缀或落款）——避免颜文字堆砌。

    比较时把 ``{词}`` 去掉，只留语言无关的符号部分（译文里不会出现中文占位词）。
    """
    for table in (VOICE_SUFFIX, SIGNOFF):
        for s in table.values():
            symbols = _PLACEHOLDER.sub("", s).strip()
            if symbols and symbols in text:
                return True
    return False


def signoff_for(kind: str | None, content: str) -> str:
    """短正文返回看板娘落款；长正文（如协议）或已带语气的正文返回空串。"""
    if not ENABLED or not kind:
        return ""
    if not isinstance(content, str) or len(content) > SIGNOFF_MAX_LEN:
        return ""
    if _has_voice(content):
        return ""
    return _render(SIGNOFF.get(kind, ""))
