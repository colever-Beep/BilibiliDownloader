"""看板娘语气层：给「展示型文案」追加 emoji / 颜文字，像看板娘在说话。

设计红线（改动前务必读）：

* 翻译键仍是简体中文原文，**绝不污染 ``utils/i18n.py`` 的 ``_LOCALES``**。
  本模块只提供「显示时追加的语气后缀」，由 ``tr()`` 在**得到译文之后**拼接。
  这样 4 语言查找、配置值 / 字典键 / 参与逻辑比较的文案都不受影响。
* 白名单 ``VOICE_SUFFIX`` 只收录**纯展示**文案（状态、空状态、提示、欢迎语）。
  配置值（``1080p``/``mp4``）、字典键、按钮回调用文字、需要精确匹配的字符串
  一律**不得**加入，否则会破坏程序逻辑。
* 带 ``{}`` 占位符的模板也可加入：``tr()`` 先格式化再拼语气，顺序安全；
  .format 参数不含花括号即可。
* 多语言：语气后缀是 emoji / 颜文字，语言无关，四种语言统一追加，
  因此无需为每种语言单独维护翻译（这就是本模块存在的意义）。

接入点（两处，均在显示层）：

1. ``utils/i18n.tr()``     —— 白名单文案追加 ``VOICE_SUFFIX``；
2. ``ui/fluent_dialog._message()`` —— 弹窗标题按 mascot_kind 加 emoji 徽标、
   短正文追加看板娘落款（见 ``badge_for`` / ``signoff_for``）。

想关掉活泼语气：把 ``ENABLED`` 设为 False 即可全局生效（便于排查问题）。
"""
from __future__ import annotations

import re

ENABLED = True

# {词} 占位：渲染时把中文语气词翻成当前语言；纯符号直接保留。
_PLACEHOLDER = re.compile(r"\{([^{}]+)\}")


def _render(raw: str) -> str:
    """把后缀模板里的 ``{词}`` 替换为当前语言译文（经纯翻译层，不递归追加语气）。"""
    if not raw or "{" not in raw:
        return raw

    def _sub(m):
        try:
            from utils.i18n import translate
            return translate(m.group(1))
        except Exception:
            return m.group(1)

    return _PLACEHOLDER.sub(_sub, raw)

